#!/usr/bin/env python3
"""Write Sources/VideoDepthAnything/Video/ColormapTables.swift from matplotlib's colormap data.

The tables are 256 sRGB entries per map, scaled to 0...255 and truncated, which is what the upstream
Video Depth Anything `save_video` writes (`(colormap[depth_norm] * 255).astype(np.uint8)`).

    python scripts/colormaps.py > Sources/VideoDepthAnything/Video/ColormapTables.swift
"""

import matplotlib
import numpy as np


def table(name):
    colors = np.array(matplotlib.colormaps[name].colors, dtype=np.float64)
    assert colors.shape == (256, 3)
    values = (colors * 255).astype(np.uint8).reshape(-1)
    rows = []
    for i in range(0, len(values), 24):
        rows.append("        " + ", ".join(str(v) for v in values[i : i + 24]) + ",")
    return "\n".join(rows)


print(f"""// Generated by scripts/colormaps.py from matplotlib {matplotlib.__version__}. Do not edit.
//
// inferno: by Nathaniel J. Smith and Stefan van der Walt, released under CC0
// (https://github.com/BIDS/colormap).
//
// turbo: Copyright 2019 Google LLC. Licensed under the Apache License, Version 2.0
// (http://www.apache.org/licenses/LICENSE-2.0); see ACKNOWLEDGEMENTS.md. Original data:
// https://gist.github.com/mikhailov-work/6a308c20e494d9e0ccc29036b28faa7a

enum ColormapTables {{
    /// 256 × RGB, sRGB.
    static let inferno: [UInt8] = [
{table("inferno")}
    ]

    /// 256 × RGB, sRGB.
    static let turbo: [UInt8] = [
{table("turbo")}
    ]
}}""")
